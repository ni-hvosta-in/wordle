create table game (
    id bigint generated by default as identity primary key,
    user_id     bigint      not null references users(id),
    target_word        varchar(20) not null,
    mode        varchar(20) not null,          -- PERSONAL (позже CHALLENGE, DUEL)
    level       varchar(5)  not null,
    status      varchar(20) not null,          -- IN_PROGRESS, WON, LOST
    started_at  timestamp not null,
    finished_at timestamp,
    version     bigint      not null default 0
);

create unique index ux_game_one_active_personal
    on game (user_id, level)
    where status = 'IN_PROGRESS' and mode = 'PERSONAL';

create index ix_game_user_level on game (user_id, level);

create table guess (
    id bigint generated by default as identity primary key,
    game_id    bigint      not null references game(id) on delete cascade,
    attempt_number int         not null,
    attempt    varchar(20) not null,
    statuses   jsonb not null,
    guessed_at timestamp not null,
    unique (game_id, attempt_number)
);